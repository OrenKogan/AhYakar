@app.route("/api/chat", methods=["POST"])
def chat():
    """Main pipeline endpoint."""
    data = request.json or {}
    user_message = (data.get("message") or "").strip()
    
    user_id = (data.get("userId") or "").strip()
    session_id = (data.get("sessionId") or user_id or data.get("session_id") or "").strip()
    location   = data.get("location")
    image_url  = data.get("imageUrl") # e.g. "/uploads/xyz.jpg"

    if not user_message and not image_url:
        return jsonify({"error": "message or image is required"}), 400
    if not session_id:
        return jsonify({"error": "sessionId is required"}), 400

    # Handle Image Data
    image_data = None
    if image_url:
        # Extract filename from URL (e.g. "/uploads/abc.jpg" -> "abc.jpg")
        filename = os.path.basename(image_url)
        local_path = os.path.join(app.config['UPLOAD_FOLDER'], filename)
        if os.path.exists(local_path):
            image_data = encode_image_to_base64(local_path)

    sess = get_session(session_id, user_id)
    sess["chat_history"].append({"role": "user", "content": user_message})

    try:
        client = get_client()

        # Generate a headline title if it doesn't exist
        if "title" not in sess and user_message:
            try:
                resp = client.chat.completions.create(
                    model="google/gemini-2.5-flash",
                    messages=[{"role": "user", "content": f"Provide a very short 2-5 word headline summarizing this medical complaint: '{user_message}'. Output only the headline."}],
                    max_tokens=20,
                    extra_headers={
                        "HTTP-Referer": "http://localhost:5000",
                        "X-OpenRouter-Title": "AhYakar",
                    }
                )
                sess["title"] = resp.choices[0].message.content.strip().replace('"', '')
            except Exception as e:
                logger.warning("Failed to generate title: %s", e)
                sess["title"] = user_message[:50] + "..."

        # ── Agent 1: Intake Analyst ──────────────────────────────────────────
        logger.info("[%s] Agent 1 — Intake Analyst (Vision: %s)", session_id[:8], bool(image_data))
        triage = intake_analyst.analyze(client, user_message, sess["chat_history"], image_data)
        sess["last_triage"] = triage
        
        # Merge memory into patient_profile
        profile = sess["patient_profile"]
        for sym in triage.get("symptoms", []):
            if sym.lower() not in [s.lower() for s in profile["symptoms"]]:
                profile["symptoms"].append(sym)
        
        if triage.get("duration") != "unknown":
            profile["duration"] = triage["duration"]
        if triage.get("relevant_history") != "none":
            profile["relevant_history"] = triage["relevant_history"]

        action1 = triage.get("action", "escalate")

        if action1 == "no_symptoms" and not profile["symptoms"]:
            reply = "I'm here to help with your health! Describe any symptoms you have."
            sess["chat_history"].append({"role": "assistant", "content": reply})
            return jsonify({
                "stage": "chat", 
                "reply": reply, 
                "requires_confirm": False,
                "thoughts": { "intake": triage }
            })

        # If we have symptoms in profile, but analyst says 'no_symptoms' for the latest word
        # (e.g. user said 'Yes' to a question), we should still escalate to advisor
        if action1 == "no_symptoms" and profile["symptoms"]:
            action1 = "escalate"

        if action1 == "home_remedy":
            reply = triage.get("home_remedy_advice") or "This sounds like it can be managed at home with rest and fluids."
            reply += "\n\n_I am an AI assistant, not a doctor._"
            sess["chat_history"].append({"role": "assistant", "content": reply})
            return jsonify({
                "stage": "home_remedy", 
                "reply": reply, 
                "requires_confirm": False,
                "thoughts": { "intake": triage }
            })

        # ── Agent 2: Clinical Diagnostician ──────────────────────────────────
        logger.info("[%s] Agent 2 — Clinical Diagnostician", session_id[:8])
        assessment = clinical_diagnostician.analyze(client, profile, sess["chat_history"], image_data)

        # ── Agent 3: Medical Advisor ─────────────────────────────────────────
        logger.info("[%s] Agent 3 — Medical Advisor", session_id[:8])
        advice = medical_advisor.advise(client, profile, assessment, sess["chat_history"])
        action2 = advice.get("action", "doctor_needed")

        # Save medications to user profile
        import datetime
        meds = advice.get("otc_medications", [])
        if meds and user_id:
            udata = get_user_data(user_id)
            current_date = datetime.datetime.now().strftime("%B %d, %Y")
            for med in meds:
                existing_texts = [m.get("text") if isinstance(m, dict) else m for m in udata["medications"]]
                if med not in existing_texts:
                    udata["medications"].append({"text": med, "date": current_date})

        if action2 == "emergency":
            reply = advice.get("reply") or "🚨 **Medical Emergency.** Call 101/911 immediately."
            sess["chat_history"].append({"role": "assistant", "content": reply})
            return jsonify({
                "stage": "emergency", 
                "reply": reply, 
                "requires_confirm": False,
                "thoughts": { "intake": triage, "advisor": advice }
            })

        if action2 == "otc":
            reply = advice.get("reply", "")
            sess["chat_history"].append({"role": "assistant", "content": reply})
            return jsonify({
                "stage": "otc", 
                "reply": reply, 
                "requires_confirm": False,
                "thoughts": { "intake": triage, "advisor": advice }
            })

        if action2 == "more_info_needed":
            reply = advice.get("reply", "")
            sess["chat_history"].append({"role": "assistant", "content": reply})
            return jsonify({"stage": "chat", "reply": reply, "requires_confirm": False})

        # Doctor needed → Agent 4: Appointment Planner
        logger.info("[%s] Agent 4 — Appointment Planner", session_id[:8])
        plan_result = appointment_planner.plan(client, triage, advice, location)
        proposal_text = plan_result.get("proposal_text", "")
        
        sess["pending_action"] = {
            "appointment_details": plan_result.get("appointment_details", {}),
            "triage": triage,
        }

        advisor_reply = advice.get("reply", "")
        full_history = advisor_reply + (f"\n\n{proposal_text}" if proposal_text else "")
        sess["chat_history"].append({"role": "assistant", "content": full_history})
        
        return jsonify({
            "stage": "doctor_needed",
            "reply": advisor_reply,
            "proposal": proposal_text,
            "requires_confirm": True,
            "thoughts": {
                "intake": triage,
                "advisor": advice,
                "planner": plan_result
            }
        })

    except Exception as exc:
        logger.exception("[%s] Pipeline error: %s", session_id[:8], exc)
        return jsonify({"error": str(exc)}), 500


@app.route("/api/confirm", methods=["POST"])
def confirm():
    """Confirmation endpoint for booking."""
    data = request.json or {}
    user_id = (data.get("userId") or "").strip()
    session_id = (data.get("sessionId") or user_id or data.get("session_id") or "").strip()
    confirmed  = bool(data.get("confirmed", False))

    if not session_id:
        return jsonify({"error": "sessionId is required"}), 400

    sess = get_session(session_id, user_id)
    pending = sess.get("pending_action")

    if not pending:
        return jsonify({"error": "No pending appointment"}), 400

    if not confirmed:
        sess["pending_action"] = None
        reply = "No problem! Let me know if you need anything else."
        sess["chat_history"].append({"role": "assistant", "content": reply})
        return jsonify({"stage": "declined", "reply": reply})

    # ── Agent 4: Executor ──────────────────────────────────────────────────
    try:
        result = executor.execute_booking(pending["appointment_details"], pending["triage"])
        sess["pending_action"] = None
        reply = result.get("message", "✅ Appointment booked!")
        sess["chat_history"].append({"role": "assistant", "content": reply})
        return jsonify({"stage": "booked", "reply": reply, "booking": result})
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


@app.route("/api/history", methods=["GET"])
def history():
    """Return chat history for a user, grouped by sessions."""
    user_id = request.args.get("userId")
    if not user_id:
        return jsonify({"error": "userId required"}), 400
        
    user_history = []
    session_ids = user_sessions.get(user_id, [])
    
    for sid in session_ids:
        sess = sessions.get(sid)
        if sess and sess["chat_history"]:
            summary = sess.get("title")
            if not summary:
                # Fallback Find first user message for the summary
                summary = "New Consultation"
                for msg in sess["chat_history"]:
                    if msg["role"] == "user":
                        summary = msg["content"]
                        break
                
                # Truncate summary if too long
                if len(summary) > 60:
                    summary = summary[:57] + "..."
                
            user_history.append({
                "sessionId": sid,
                "summary": summary,
                "messages": sess["chat_history"]
            })
            
    # Reverse so newest are first
    user_history.reverse()
    
    return jsonify({"history": user_history})


@app.route("/api/medications", methods=["GET", "POST"])
def medications():
    """Handle user medication list."""
    if request.method == "POST":
        data = request.json or {}
        user_id = data.get("userId")
        meds = data.get("medications", [])
        if not user_id:
            return jsonify({"error": "userId required"}), 400
        udata = get_user_data(user_id)
        udata["medications"] = meds
        return jsonify({"success": True})
    
    user_id = request.args.get("userId")
    if not user_id:
        return jsonify({"error": "userId required"}), 400
    udata = get_user_data(user_id)
    return jsonify({"medications": udata.get("medications", [])})




@app.route("/api/upload", methods=["POST"])
def upload_file():
    """Handle file uploads."""
    if 'file' not in request.files:
        return jsonify({"error": "No file part"}), 400
    file = request.files['file']
    if file.filename == '':
        return jsonify({"error": "No selected file"}), 400
    
    if file:
        filename = secure_filename(file.filename)
        unique_filename = f"{uuid.uuid4().hex}_{filename}"
        file.save(os.path.join(app.config['UPLOAD_FOLDER'], unique_filename))
        return jsonify({
            "success": True, 
            "filename": filename,
            "path": unique_filename,
            "url": f"/uploads/{unique_filename}"
        })

@app.route('/uploads/<filename>')
def uploaded_file(filename):
    return send_from_directory(app.config['UPLOAD_FOLDER'], filename)


@app.route("/api/reset", methods=["POST"])
def reset():
    """Clear session data for a new consultation."""
    data = request.json or {}
    session_id = (data.get("userId") or data.get("session_id") or "").strip()
    if not session_id:
        return jsonify({"error": "userId required"}), 400
    
    if session_id in sessions:
        sessions[session_id] = {
            "chat_history": [],
            "pending_action": None,
            "last_triage": None,
            "patient_profile": {
                "symptoms": [],
                "duration": "unknown",
                "relevant_history": "none",
                "medications": []
            }
        }
    return jsonify({"success": True})



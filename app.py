"""
AhYakar — Multi-Agent Medical Assistant
========================================
Flask backend that orchestrates the four-agent pipeline:

  [1] Intake Analyst      — gatekeeper: home remedy vs escalate vs no-symptoms
  [2] Medical Advisor     — deep clinical analysis: OTC vs doctor vs emergency
  [3] Appointment Planner — finds nearest available doctor using patient location
  [4] Executor            — calls the booking API after user confirms

Session state is kept in-memory, keyed by a UUID generated by the browser
and persisted in localStorage for the duration of the tab/conversation.
"""


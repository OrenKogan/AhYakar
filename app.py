# ── OpenRouter client (lazy-initialized on first request) ──────────────────
_client: OpenAI | None = None

def get_client() -> OpenAI:
    """Return the singleton OpenRouter client, creating it on first call."""
    global _client
    if _client is None:
        api_key = os.getenv("OPENROUTER_API_KEY")
        if not api_key:
            raise RuntimeError(
                "OPENROUTER_API_KEY environment variable is not set. "
                "Please set it before starting the server."
            )
        _client = OpenAI(
            base_url="https://openrouter.ai/api/v1",
            api_key=api_key,
        )
    return _client

import json

APP_DATA_DIR = 'app_data'
if not os.path.exists(APP_DATA_DIR):
    os.makedirs(APP_DATA_DIR)
DB_FILE = os.path.join(APP_DATA_DIR, 'db.json')

# ── Persistent session store ───────────────────────────────────────────────────
# Structure: { session_id: { chat_history, pending_action, last_triage } }
sessions: dict[str, dict] = {}
user_sessions: dict[str, list[str]] = {}
user_data: dict[str, dict] = {}

def load_state():
    global sessions, user_sessions, user_data
    if os.path.exists(DB_FILE):
        try:
            with open(DB_FILE, 'r', encoding='utf-8') as f:
                data = json.load(f)
                sessions = data.get('sessions', {})
                user_sessions = data.get('user_sessions', {})
                user_data = data.get('user_data', {})
        except Exception as e:
            logger.error("Failed to load state: %s", e)

def save_state():
    try:
        with open(DB_FILE, 'w', encoding='utf-8') as f:
            json.dump({
                'sessions': sessions,
                'user_sessions': user_sessions,
                'user_data': user_data
            }, f, ensure_ascii=False, indent=2)
    except Exception as e:
        logger.error("Failed to save state: %s", e)

load_state()

@app.after_request
def auto_save(response):
    if request.path.startswith('/api/'):
        save_state()
    return response

def get_user_data(user_id: str) -> dict:
    if user_id not in user_data:
        user_data[user_id] = {"medications": []}
    return user_data[user_id]

def get_session(session_id: str, user_id: str = None) -> dict:
    """Return (creating if needed) the session state for the given ID."""
    if session_id not in sessions:
        sessions[session_id] = {
            "chat_history": [],
            "pending_action": None,
            "last_triage": None,
            "patient_profile": {
                "symptoms": [],
                "duration": "unknown",
                "relevant_history": "none",
                "medications": []
            }
        }
        if user_id:
            if user_id not in user_sessions:
                user_sessions[user_id] = []
            if session_id not in user_sessions[user_id]:
                user_sessions[user_id].append(session_id)
    return sessions[session_id]



# ── OpenRouter client (lazy-initialized on first request) ──────────────────
_client: OpenAI | None = None

def get_client() -> OpenAI:
    """Return the singleton OpenRouter client, creating it on first call."""
    global _client
    if _client is None:
        api_key = os.getenv("OPENROUTER_API_KEY")
        if not api_key:
            raise RuntimeError(
                "OPENROUTER_API_KEY environment variable is not set. "
                "Please set it before starting the server."
            )
        _client = OpenAI(
            base_url="https://openrouter.ai/api/v1",
            api_key=api_key,
        )
    return _client

def encode_image_to_base64(path: str) -> str:
    """Read a local file and return its base64 representation."""
    try:
        with open(path, "rb") as image_file:
            return base64.b64encode(image_file.read()).decode('utf-8')
    except Exception as e:
        logger.error("Failed to encode image: %s", e)
        return None

# ── In-memory session store ───────────────────────────────────────────────────
# Structure: { session_id: { chat_history, pending_action, last_triage } }
sessions: dict[str, dict] = {}
user_sessions: dict[str, list[str]] = {}
user_data: dict[str, dict] = {}

def get_user_data(user_id: str) -> dict:
    if user_id not in user_data:
        user_data[user_id] = {"medications": []}
    return user_data[user_id]

def get_session(session_id: str, user_id: str = None) -> dict:
    """Return (creating if needed) the session state for the given ID."""
    if session_id not in sessions:
        sessions[session_id] = {
            "chat_history": [],
            "pending_action": None,
            "last_triage": None,
            "patient_profile": {
                "symptoms": [],
                "duration": "unknown",
                "relevant_history": "none",
                "medications": []
            }
        }
        if user_id:
            if user_id not in user_sessions:
                user_sessions[user_id] = []
            if session_id not in user_sessions[user_id]:
                user_sessions[user_id].append(session_id)
    return sessions[session_id]


